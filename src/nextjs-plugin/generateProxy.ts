import {
    existsSync,
    readFileSync,
    readdirSync,
    writeFileSync,
    unlinkSync,
    watchFile,
    unwatchFile,
    renameSync
} from "node:fs";
import { resolve, join, relative, dirname } from "node:path";
import type { NextConfig } from "next";
import { getPagesPageStaticInfo } from "next/dist/build/analysis/get-page-static-info.js";
import { PAGE_TYPES } from "next/dist/lib/page-types.js";
import { loadBindings } from "next/dist/build/swc/index.js";
import { buildValidRedirectUri } from "../core/earlyInit_homeUrlAndValidRedirectUri";

const GENERATED_MARKER = "// Generated by oidc-spa/nextjs-plugin. Do not edit this file.";
const watchers = new Map<
    string,
    {
        params: Parameters<typeof generateProxy>[0];
        path: string;
        listener: () => void;
    }
>();

export async function generateProxy(params: {
    projectRoot: string;
    nextConfig: NextConfig;
    proxy: string | undefined;
    isDev: boolean;
}): Promise<void> {
    const { nextConfig, proxy, isDev } = params;
    const projectRoot = resolve(params.projectRoot);
    const watcher = watchers.get(projectRoot);
    if (watcher !== undefined) {
        if (!isDev || watcher.path !== (proxy === undefined ? undefined : resolve(projectRoot, proxy))) {
            unwatchFile(watcher.path, watcher.listener);
            watchers.delete(projectRoot);
        } else {
            watcher.params = params;
        }
    }
    const extensions = nextConfig.pageExtensions ?? ["tsx", "ts", "jsx", "js"];
    const sourceDir = [projectRoot, join(projectRoot, "src")].find(dir =>
        ["app", "pages"].some(name => existsSync(join(dir, name)))
    );

    if (sourceDir === undefined) {
        throw new Error(
            `oidc-spa: Could not find app/ or pages/ in ${projectRoot}. ` +
                "Set projectRoot in withOidcSpa() when running Next from another directory."
        );
    }

    const preferredExtensions = existsSync(join(projectRoot, "tsconfig.json"))
        ? ["ts", "tsx", "js", "jsx"]
        : ["js", "jsx", "ts", "tsx"];
    const extension = preferredExtensions
        .map(preferred => extensions.find(ext => ext === preferred || ext.endsWith(`.${preferred}`)))
        .find(ext => ext !== undefined);

    if (extension === undefined) {
        throw new Error(
            "oidc-spa: pageExtensions must include a JavaScript or TypeScript extension to generate proxy."
        );
    }

    const proxyPath = join(sourceDir, `proxy.${extension}`);
    const proxy_user_path = proxy === undefined ? undefined : resolve(projectRoot, proxy);
    const managedPaths: string[] = [];

    for (const dir of [projectRoot, join(projectRoot, "src")]) {
        if (!existsSync(dir)) {
            continue;
        }
        for (const file of readdirSync(dir)) {
            if (!extensions.some(ext => file === `proxy.${ext}` || file === `middleware.${ext}`)) {
                continue;
            }
            const filePath = join(dir, file);
            if (readFileSync(filePath, "utf8").startsWith(GENERATED_MARKER)) {
                managedPaths.push(filePath);
                continue;
            }
            throw new Error(
                `oidc-spa: ${relative(
                    projectRoot,
                    filePath
                )} already exists and will not be overwritten. ` +
                    "Rename it (for example to my-proxy.ts) and set proxy: './my-proxy.ts' in withOidcSpa(). " +
                    "Keep its handler and config exports in that module."
            );
        }
    }

    if (
        proxy_user_path === proxyPath ||
        (proxy_user_path !== undefined && managedPaths.includes(proxy_user_path))
    ) {
        throw new Error(
            "oidc-spa: The custom proxy must be a separate module, not the generated proxy file."
        );
    }
    if (proxy_user_path !== undefined && !existsSync(proxy_user_path)) {
        throw new Error(`oidc-spa: Custom proxy module not found: ${proxy_user_path}`);
    }

    if (proxy_user_path !== undefined) {
        // Config evaluation precedes Next's usual initialization of its parser.
        await loadBindings();
    }
    const userConfig =
        proxy_user_path === undefined
            ? undefined
            : await getPagesPageStaticInfo({
                  pageFilePath: proxy_user_path,
                  nextConfig,
                  isDev,
                  page: "/proxy",
                  pageType: PAGE_TYPES.ROOT
              });

    if (userConfig?.hadUnsupportedValue) {
        throw new Error(
            "oidc-spa: The custom proxy config must use statically analyzable literals, as required by Next.js."
        );
    }

    const userMatchers = userConfig?.middleware?.matchers;
    const callbackMatcher = (() => {
        const homeMatcher = { source: "/", has: [{ type: "query", key: "state" }] };
        try {
            const homeUrl = new URL(`${nextConfig.basePath ?? ""}/`, "http://localhost");
            const validRedirectUri = new URL(
                buildValidRedirectUri({
                    homeUrl: homeUrl.href,
                    redirectUriPath: nextConfig.env?.OIDC_SPA_NEXTJS_REDIRECT_URI_PATH ?? "/"
                })
            );
            // Next adds basePath to matchers. Escape the remaining literal path
            // so callback names cannot become matcher patterns.
            const callbackPath = validRedirectUri.pathname.slice(homeUrl.pathname.length - 1);
            if (callbackPath === "/") return homeMatcher;
            return { source: callbackPath.replace(/[.*+?^${}()|[\]\\:]/g, "\\$&") };
        } catch {
            // The client reports invalid callback configuration in detail.
            return homeMatcher;
        }
    })();
    const matcher =
        proxy_user_path === undefined
            ? [callbackMatcher]
            : userMatchers === undefined
            ? ["/:path*"]
            : [
                  callbackMatcher,
                  ...userMatchers.map(({ originalSource, regexp, ...rest }) => ({
                      source: originalSource,
                      ...rest
                  }))
              ];
    const source = [
        GENERATED_MARKER,
        "/* eslint-disable */",
        "// @ts-nocheck",
        "// noinspection JSUnusedGlobalSymbols",
        "// @formatter:off",
        "",
        "// This file is regenerated during next dev and next build. Changes will be overwritten.",
        "// To customize proxy behavior:",
        "// 1. Create a separate module (for example my-proxy.ts) with a named `proxy`",
        "//    or default function export. Keep its optional literal `config` export there.",
        "// 2. Add that module's path to the options passed to withOidcSpa() in your",
        "//    next.config.ts (or next.config.js/mjs):",
        `//    export default withOidcSpa(nextConfig, { proxy: ${JSON.stringify(
            proxy ?? "./my-proxy.ts"
        )} });`,
        "//    Keep your other oidc-spa options alongside `proxy`.",
        "// The plugin combines your handler and matcher with OIDC callback handling automatically.",
        ...(proxy === undefined
            ? []
            : [
                  `// Your custom proxy module: ${JSON.stringify(
                      proxy
                  )}. Edit that module, not this file.`
              ]),
        "// This generated file is excluded from Prettier through .prettierignore.",
        "",
        ...(proxy_user_path === undefined
            ? ['export { proxy } from "oidc-spa/nextjs-plugin/proxy";']
            : [
                  'import { withOidcSpaProxy } from "oidc-spa/nextjs-plugin/proxy";',
                  `import * as userProxy from ${JSON.stringify(
                      `./${relative(dirname(proxyPath), proxy_user_path)
                          .replace(/\\/g, "/")
                          .replace(/\.(?:tsx?|jsx?)$/, "")}`
                  )};`,
                  `export const proxy = withOidcSpaProxy(userProxy, ${JSON.stringify(userMatchers)});`
              ]
        ).flatMap(statement => ["// prettier-ignore", statement, ""]),
        "// prettier-ignore",
        `export const config = ${JSON.stringify(
            {
                matcher,
                regions: userConfig?.middleware?.regions,
                unstable_allowDynamic: userConfig?.middleware?.unstable_allowDynamic
            },
            null,
            4
        )};`,
        ""
    ].join("\n");

    if (!existsSync(proxyPath) || readFileSync(proxyPath, "utf8") !== source) {
        const temporaryPath = `${proxyPath}.${process.pid}.tmp`;
        writeFileSync(temporaryPath, source);
        renameSync(temporaryPath, proxyPath);
    }
    for (const managedPath of managedPaths) {
        if (managedPath !== proxyPath) {
            unlinkSync(managedPath);
        }
    }

    const ignoredPath = `/${relative(projectRoot, proxyPath).replace(/\\/g, "/")}`;
    for (const filename of [".gitignore", ".prettierignore"]) {
        const ignorePath = join(projectRoot, filename);
        const ignore = existsSync(ignorePath) ? readFileSync(ignorePath, "utf8") : "";
        if (!ignore.split(/\r?\n/).some(line => line.trim() === ignoredPath)) {
            writeFileSync(
                ignorePath,
                `${ignore}${
                    ignore.endsWith("\n") || ignore === "" ? "" : "\n"
                }\n# Generated by oidc-spa/nextjs-plugin\n${ignoredPath}\n`
            );
        }
    }

    if (isDev && proxy_user_path !== undefined && !watchers.has(projectRoot)) {
        let update = Promise.resolve();
        const watcher = {
            params,
            path: proxy_user_path,
            listener: () => {
                update = update
                    .then(() => generateProxy(watcher.params))
                    .catch(error => {
                        console.error("oidc-spa: Could not update the generated proxy:", error);
                    });
            }
        };
        watchFile(proxy_user_path, { persistent: false, interval: 250 }, watcher.listener);
        watchers.set(projectRoot, watcher);
    }
}
